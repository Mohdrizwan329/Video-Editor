import 'dart:io';

import 'package:flutter/foundation.dart';

import '../models/hsl_grade.dart';

/// Bakes an [HslGrade] into a 3D lookup table for the exporter.
///
/// FFmpeg has no per-hue-band grade of its own: `hue` is global, and
/// `selectivecolor` works on a fixed set of primaries in CMYK, neither of
/// which is what this tool does. A LUT sidesteps that entirely — the grade is
/// evaluated once per grid point here, in the same Dart the preview shader
/// mirrors, and `lut3d` interpolates the rest. It is also the fast path:
/// per-pixel arithmetic in `geq` would cost minutes a clip.
class HslLut {
  const HslLut._();

  /// Points per axis. 33 is the size the grading tools settled on: fine
  /// enough that the interpolation between points is invisible, small enough
  /// that the file stays under a megabyte and bakes in a blink.
  static const int size = 33;

  /// The `.cube` text for [grade].
  ///
  /// Red runs fastest and blue slowest, which is the order the format
  /// specifies — getting it backwards produces a file that loads without
  /// complaint and grades the wrong colours.
  static String cube(HslGrade grade) {
    final b = StringBuffer()
      ..writeln('# Generated by Video Editor — HSL grade')
      ..writeln('LUT_3D_SIZE $size')
      ..writeln('DOMAIN_MIN 0.0 0.0 0.0')
      ..writeln('DOMAIN_MAX 1.0 1.0 1.0');
    const last = size - 1;
    for (var bi = 0; bi < size; bi++) {
      for (var gi = 0; gi < size; gi++) {
        for (var ri = 0; ri < size; ri++) {
          final (r, g, bl) = grade.apply(ri / last, gi / last, bi / last);
          b.writeln(
            '${r.toStringAsFixed(6)} '
            '${g.toStringAsFixed(6)} '
            '${bl.toStringAsFixed(6)}',
          );
        }
      }
    }
    return b.toString();
  }

  /// Write [grade] to a `.cube` beside the export and hand back its path, or
  /// null when there is nothing to bake or the file cannot be written.
  static Future<String?> write(HslGrade grade, Directory dir) async {
    if (grade.isNeutral) return null;
    try {
      final file = File(
        '${dir.path}/hsl_${DateTime.now().microsecondsSinceEpoch}.cube',
      );
      await file.writeAsString(cube(grade), flush: true);
      return file.path;
    } catch (e) {
      debugPrint('could not write the HSL LUT: $e');
      return null;
    }
  }
}
